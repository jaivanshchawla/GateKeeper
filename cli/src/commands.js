export function version() {
  const path = new URL('../package.json', import.meta.url)
  return JSON.parse(readFileSync(path, 'utf-8')).version
}

const BANNER = '🛡️  Gatekeeper'

/**
 * True when something other than .git/hooks owns this repo's hooks.
 * husky points core.hooksPath at .husky/_, so a raw .git/hooks/pre-push would
 * be silently dead code.
 */
export function detectHookManager(gitRoot) {
  if (existsSync(join(gitRoot, '.husky'))) return true
  try {
    const hooksPath = execSync('git config --get core.hooksPath', {
      cwd: gitRoot,
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim()
    return hooksPath.length > 0
  } catch {
    return false
  }
}

/**
 * A pre-push hook that works however the CLI was installed: globally, as a
 * project devDependency, or from a source checkout. Baking an absolute path
 * into the hook is what makes installed CLIs break when node_modules moves.
 */
export function hookScript() {
  return `#!/bin/sh
# Gatekeeper pre-push hook (generated by \`gatekeeper init\`)
# Scores outgoing commits and blocks only on block-severity findings.
# Skip once with: SKIP=gatekeeper-score git push

if [ "$SKIP" = "gatekeeper-score" ] || [ "$SKIP" = "all" ]; then
  exit 0
fi

root=$(git rev-parse --show-toplevel 2>/dev/null) || exit 0

echo "🛡️  Gatekeeper: scoring outgoing commits..."

if command -v gatekeeper >/dev/null 2>&1; then
  gatekeeper check
  exit $?
fi

if [ -x "$root/node_modules/.bin/gatekeeper" ]; then
  "$root/node_modules/.bin/gatekeeper" check
  exit $?
fi

if command -v npx >/dev/null 2>&1; then
  npx --no-install gatekeeper check
  exit $?
fi

echo "Gatekeeper: CLI not found; skipping."
exit 0
`
}

export function cmdInit({ cwd, out = console.log } = {}) {
  const gitRoot = getGitRoot(cwd)
  if (!gitRoot) {
    console.error('❌ Not inside a git repository.')
    return 1
  }

  const configPath = join(gitRoot, '.gatekeeper.yml')
  if (!existsSync(configPath)) {
    writeFileSync(configPath, DEFAULT_CONFIG_YAML)
    out('✅ Created .gatekeeper.yml')
  } else {
    out('ℹ  .gatekeeper.yml already exists, skipping.')
  }

  if (detectHookManager(gitRoot)) {
    out('ℹ  husky manages git hooks in this repo — leaving .git/hooks alone.')
    out('   Gate 1 is wired into .husky/pre-push. Install it with: npm install')
  } else {
    const hookPath = join(gitRoot, '.git', 'hooks', 'pre-push')
    writeFileSync(hookPath, hookScript(), { mode: 0o755 })
    out('✅ Installed pre-push hook')
  }

  const remoteUrl = getGitRemoteUrl(gitRoot)
  const repoName = repoNameFromRemote(remoteUrl)
  if (repoName) {
    const userConfig = loadUserConfig()
    userConfig.repos = userConfig.repos || {}
    userConfig.repos[repoName] = {
      remote_url: remoteUrl,
      registered_at: new Date().toISOString(),
    }
    saveUserConfig(userConfig)
    out(`✅ Registered repo: ${repoName}`)
  }

  out('\n🎯 Gatekeeper initialized. Run `gatekeeper check` to score unpushed commits.')
  return 0
}

function bandOf(violations, ml) {
  if (violations.some((v) => v.severity === 'block')) return 'high'
  if (ml?.risk_label) return ml.risk_label
  return violations.length > 0 ? 'medium' : 'low'
}

/**
 * Score every unpushed commit.
 *
 * Deterministic rules always run. The model runs when an API URL is
 * configured and `ml_scoring.enabled` is true, and its band is what the output
 * shows -- the rules decide whether a push is blocked, which is the promise
 * the hook makes.
 */
export async function cmdCheck({
  cwd,
  argv = [],
  out = console.log,
  env = process.env,
  userConfig = loadUserConfig(),
} = {}) {
  const gitRoot = getGitRoot(cwd)
  if (!gitRoot) {
    console.error('❌ Not inside a git repository.')
    return 1
  }

  const commits = getUnpushedCommits(gitRoot)
  const jsonMode = argv.includes('--json')
  const config = getEffectiveConfig(gitRoot)
  const repoName = getRepoName(gitRoot) || 'unknown'
  const apiConfigured = Boolean(resolveApiUrl(userConfig, env))
  const useModel = Boolean(config.ml_scoring?.enabled) && apiConfigured

  if (commits.length === 0) {
    if (jsonMode) {
      out(JSON.stringify({ version: version(), repo: repoName, commits: [], summary: emptySummary() }, null, 2))
    } else {
      out('✅ No unpushed commits to score.')
    }
    return 0
  }

  if (!jsonMode) {
    out(
      `\n${BANNER}: scoring ${commits.length} unpushed commit(s)` +
        `${useModel ? ' (rules, plus the model when the API answers)' : ' (local rules)'}\n`,
    )
  }

  const results = []
  let blocked = false

  for (const { sha, message } of commits) {
    const diff = commitDiff(gitRoot, sha)
    const violations = evaluate(gitRoot, diff, config)
    let ml = null
    if (useModel) {
      const features = buildFeatures(diff, {
        authorPriorCommits: authorPriorCommits(gitRoot, diff.email),
      })
      try {
        ml = await scoreCommit(features, repoName, { userConfig, env })
      } catch (error) {
        if (error instanceof ApiError && error.status === 401) {
          console.error(`❌ ${error.message}`)
          console.error('   The API requires a session. Run `gatekeeper auth --token <jwt>` or set GATEKEEPER_TOKEN.')
          return 1
        }
        throw error
      }
    }

    const band = bandOf(violations, ml)
    const hasBlocker = violations.some((v) => v.severity === 'block')
    if (hasBlocker) blocked = true

    results.push({
      sha,
      message: message || diff.message,
      band,
      score: ml?.risk_score ?? null,
      files_changed: diff.files.map((f) => f.path),
      lines_added: diff.linesAdded,
      lines_deleted: diff.linesDeleted,
      rule_results: violations.map((v) => ({
        rule: v.rule,
        severity: v.severity,
        passed: false,
        message: v.message,
      })),
      explanations: (ml?.explanations || []).map((e) => e.human_readable || e.description),
      has_blocker: hasBlocker,
    })

    if (!jsonMode) {
      const shortSha = sha.slice(0, 8)
      const label = message.slice(0, 60)
      const icon = hasBlocker ? '🚫' : band === 'high' ? '🔴' : band === 'medium' ? '🟡' : '✅'
      const score = ml?.risk_score != null ? ` (score ${ml.risk_score.toFixed(3)})` : ''
      out(`  ${icon} ${shortSha} ${label}${score}`)
      for (const v of violations) {
        out(`     [${v.severity.toUpperCase()}] ${v.rule}: ${v.message}`)
      }
      for (const factor of results.at(-1).explanations.slice(0, 3)) {
        out(`     ↳ ${factor}`)
      }
    }
  }

  const summary = {
    total: results.length,
    passed: results.filter((r) => !r.has_blocker && r.rule_results.length === 0).length,
    warnings: results.filter((r) => !r.has_blocker && r.rule_results.length > 0).length,
    blocked: results.filter((r) => r.has_blocker).length,
  }

  if (jsonMode) {
    out(JSON.stringify({
      version: version(),
      repo: repoName,
      commits: results,
      summary,
      config: {
        ml_scoring: Boolean(config.ml_scoring?.enabled),
        model_used: useModel,
        fail_on: config.fail_on || ['block'],
      },
    }, null, 2))
  } else {
    out('')
  }

  const failsOnBlock = (config.fail_on || ['block']).includes('block')
  if (blocked && failsOnBlock) {
    if (!jsonMode) {
      out('🚫 Push blocked by Gatekeeper (a block-severity rule triggered).')
      out('   Fix the findings above, or skip once with: SKIP=gatekeeper-score git push')
    }
    return 1
  }
  if (!jsonMode) out(`Done. ${results.length} commit(s) scored.`)
  return 0
}

function evaluate(gitRoot, diff, config) {
  const violations = evaluateRules(diff, config)
  // direct_to_main needs the branch, not the diff.
  const branch = getCurrentBranch(gitRoot)
  const directToMain = config.rules?.direct_to_main
  if (directToMain && (branch === 'main' || branch === 'master')) {
    violations.push({
      rule: 'direct_to_main',
      severity: directToMain.severity || 'warn',
      message: `Commit lands directly on ${branch}`,
    })
  }
  return violations
}

function emptySummary() {
  return { total: 0, passed: 0, warnings: 0, blocked: 0 }
}

export async function cmdStatus({
  cwd,
  out = console.log,
  env = process.env,
  userConfig = loadUserConfig(),
} = {}) {
  const repoName = getRepoName(cwd)
  if (!repoName) {
    console.error('❌ No git remote configured.')
    return 1
  }
  if (!resolveApiUrl(userConfig, env)) {
    out(`📦 Repo: ${repoName}`)
    out('ℹ  No API URL configured. Set it with:')
    out('   gatekeeper config --api-url https://your-api.example.com')
    return 0
  }

  out(`${BANNER} status for ${repoName}...\n`)
  let data
  try {
    data = await request(`/issues?repo=${encodeURIComponent(repoName)}`, { userConfig, env })
  } catch (error) {
    if (error instanceof ApiError && error.status === 401) {
      console.error('❌ The API requires a session. Run `gatekeeper auth --token <jwt>`.')
      return 1
    }
    console.warn(`⚠  ${error.message}`)
    return 0
  }

  const issues = Array.isArray(data) ? data : data.issues || []
  const open = issues.filter((i) => i.status === 'open')
  const resolved = issues.filter((i) => i.status === 'resolved')
  out(`  Open issues:     ${open.length}`)
  out(`  Resolved issues: ${resolved.length}`)
  for (const issue of open.slice(-5)) {
    out(`    [Gate ${issue.gate}] ${issue.type}: ${String(issue.details || 'no details').slice(0, 80)}`)
  }
  return 0
}

export async function cmdExplain(sha, {
  cwd,
  out = console.log,
  env = process.env,
  userConfig = loadUserConfig(),
} = {}) {
  if (!sha) {
    console.error('Usage: gatekeeper explain <commit-sha>')
    return 1
  }
  const gitRoot = getGitRoot(cwd)
  if (!gitRoot) {
    console.error('❌ Not inside a git repository.')
    return 1
  }

  const diff = commitDiff(gitRoot, sha)
  if (!diff.message) {
    console.error(`❌ Could not read commit ${sha}.`)
    return 1
  }

  const repoName = getRepoName(gitRoot) || 'unknown'
  out(`\n${BANNER} explain ${sha.slice(0, 12)} (${repoName})\n`)
  out(`  Author:  ${diff.author} <${diff.email}>`)
  out(`  Date:    ${diff.date}`)
  out(`  Message: ${diff.message}`)
  out(`  Changes: ${diff.files.length} file(s), +${diff.linesAdded}/-${diff.linesDeleted}`)

  if (!resolveApiUrl(userConfig, env)) {
    out('\n  ℹ  No API URL configured, so no model score was requested.')
    out('     gatekeeper config --api-url https://your-api.example.com')
    return 0
  }

  let score
  try {
    const features = buildFeatures(diff, {
      authorPriorCommits: authorPriorCommits(gitRoot, diff.email),
    })
    score = await request('/predict', {
      method: 'POST',
      body: { features, repo_name: repoName },
      userConfig,
      env,
    })
  } catch (error) {
    if (error instanceof ApiError && error.status === 401) {
      console.error('❌ The API requires a session. Run `gatekeeper auth --token <jwt>`.')
      return 1
    }
    console.warn(`⚠  ${error.message}`)
    return 0
  }

  out(`\n  Band:    ${String(score.risk_label || 'unknown').toUpperCase()}`)
  out(`  Score:   ${Number(score.risk_score).toFixed(4)}`)
  for (const explanation of score.explanations || []) {
    out(`    • ${explanation.human_readable || explanation.description}`)
  }
  return 0
}

export function cmdConfig(args, { cwd, out = console.log } = {}) {
  const userConfig = loadUserConfig()
  if (args.includes('--api-url')) {
    const url = args[args.indexOf('--api-url') + 1]
    if (!url) {
      console.error('Usage: gatekeeper config --api-url <url>')
      return 1
    }
    userConfig.api_url = url
    saveUserConfig(userConfig)
    out(`✅ API URL set to: ${url}`)
    return 0
  }

  const gitRoot = getGitRoot(cwd)
  const effective = gitRoot ? getEffectiveConfig(gitRoot) : getEffectiveConfig(null)
  out('\n📋 Effective Gatekeeper configuration:\n')
  out(`  Repo config: ${gitRoot && loadRepoConfig(gitRoot) ? join(gitRoot, '.gatekeeper.yml') : '(none — using defaults)'}`)
  out(`  API URL: ${resolveApiUrl(userConfig) || '(not set)'}`)
  out(`  Session token: ${resolveToken(userConfig) ? '(set)' : '(not set)'}`)
  out(`  ML scoring: ${effective.ml_scoring?.enabled ? 'enabled' : 'disabled'}`)
  out(`  Fail on: ${(effective.fail_on || ['block']).join(', ')}`)
  out('\n  Rules:')
  for (const [name, cfg] of Object.entries(effective.rules)) {
    const limit = cfg.max_lines ? ` (max: ${cfg.max_lines})` : cfg.max_files ? ` (max: ${cfg.max_files})` : ''
    out(`    ${name}: ${cfg.severity || 'warn'}${limit}`)
  }
  return 0
}

/**
 * Store or clear the API session token.
 *
 * Verified before it is saved: a typo'd or expired token that silently fails
 * at the next push is worse than a command that says no now.
 */
export async function cmdAuth(args, { out = console.log } = {}) {
  const userConfig = loadUserConfig()

  if (args.includes('--clear')) {
    delete userConfig.token
    saveUserConfig(userConfig)
    out('✅ Session token cleared.')
    return 0
  }

  if (!args.includes('--token')) {
    out('Usage: gatekeeper auth --token <clerk-session-jwt>')
    out('       gatekeeper auth --clear')
    out('\nCI: set GATEKEEPER_TOKEN instead of saving one to disk.')
    return args.length === 0 ? 0 : 1
  }

  const token = args[args.indexOf('--token') + 1]
  if (!token) {
    console.error('Usage: gatekeeper auth --token <clerk-session-jwt>')
    return 1
  }

  let me
  try {
    me = await request('/auth/me', { env: { ...process.env, GATEKEEPER_TOKEN: token } })
  } catch (error) {
    console.error(`❌ Token rejected: ${error.message}`)
    return 1
  }
  if (!me?.authenticated) {
    console.error('❌ The API did not accept that token (auth may be disabled there).')
    return 1
  }

  userConfig.token = token
  saveUserConfig(userConfig)
  out(`✅ Signed in as ${me.user?.email || me.user?.user_id}`)
  return 0
}

export async function cmdWhoami({
  out = console.log,
  env = process.env,
  userConfig = loadUserConfig(),
} = {}) {
  if (!resolveApiUrl(userConfig, env)) {
    out('ℹ  No API URL configured.')
    return 0
  }
  let me
  try {
    me = await request('/auth/me', { userConfig, env })
  } catch (error) {
    if (error instanceof ApiError && error.status === 401) {
      console.error('❌ Not signed in. Run `gatekeeper auth --token <jwt>`.')
      return 1
    }
    console.error(`❌ ${error.message}`)
    return 1
  }
  if (!me.authenticated) {
    out(`ℹ  Authentication is ${me.mode} on this API; nobody is signed in.`)
    return 0
  }
  out(`👤 ${me.user.email || me.user.user_id}${me.user.org_id ? ` (org ${me.user.org_id})` : ''}`)
  return 0
}
